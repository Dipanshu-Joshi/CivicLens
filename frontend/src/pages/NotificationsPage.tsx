import { useState } from 'react'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { Link } from 'react-router-dom'
import { AppLayout } from '../components/AppLayout'
import { Icon } from '../components/Icon'
import { Badge, Button, Card, PageHeader, StatePanel } from '../components/ui'
import {
  getUnreadNotificationCount,
  listNotifications,
  markAllNotificationsRead,
  markNotificationRead,
} from '../lib/api/citizen'
import { errorMessage } from '../lib/api/errors'
import { useAuth } from '../lib/auth/AuthContext'
import { complaintPathForRole } from '../lib/notifications'
import { formatDateTime, humanizeStatus } from '../lib/utils/format'

export default function NotificationsPage() {
  const queryClient = useQueryClient()
  const { user } = useAuth()
  const [unreadOnly, setUnreadOnly] = useState(false)

  const notifications = useQuery({
    queryKey: ['notifications', 'list'],
    queryFn: listNotifications,
    refetchInterval: 30_000,
  })
  const unread = useQuery({
    queryKey: ['notifications', 'unread'],
    queryFn: getUnreadNotificationCount,
    refetchInterval: 30_000,
    retry: false,
  })

  const invalidate = async () => {
    await Promise.all([
      queryClient.invalidateQueries({ queryKey: ['notifications', 'list'] }),
      queryClient.invalidateQueries({ queryKey: ['notifications', 'unread'] }),
    ])
  }

  const markOne = useMutation({
    mutationFn: markNotificationRead,
    onSuccess: invalidate,
  })
  const markAll = useMutation({
    mutationFn: markAllNotificationsRead,
    onSuccess: invalidate,
  })

  const items = (notifications.data ?? []).filter(
    (notification) => !unreadOnly || !notification.readAt,
  )
  const listUnreadCount = (notifications.data ?? []).filter((notification) => !notification.readAt)
    .length
  const unreadCount = unread.data ?? listUnreadCount

  return (
    <AppLayout>
      <PageHeader
        eyebrow="Stay informed"
        title="Notifications"
        description="Updates generated by the backend for your account."
        actions={
          <>
            <Button
              variant="secondary"
              size="sm"
              loading={notifications.isFetching}
              onClick={() => void notifications.refetch()}
            >
              Refresh
            </Button>
            <Button
              variant={unreadOnly ? 'primary' : 'secondary'}
              size="sm"
              onClick={() => setUnreadOnly((value) => !value)}
            >
              Unread only {unreadCount > 0 ? `(${unreadCount})` : ''}
            </Button>
            <Button
              variant="secondary"
              size="sm"
              loading={markAll.isPending}
              disabled={unreadCount === 0}
              onClick={() => markAll.mutate()}
            >
              Mark all read
            </Button>
          </>
        }
      />

      {notifications.isPending && (
        <Card className="p-10 text-center text-sm text-stone-500">Loading notifications…</Card>
      )}

      {notifications.isError && (
        <StatePanel
          tone="error"
          title="Could not load notifications"
          description={errorMessage(notifications.error, 'The service did not return notifications.')}
          action={
            <Button variant="secondary" onClick={() => void notifications.refetch()}>
              Try again
            </Button>
          }
        />
      )}

      {notifications.isSuccess && items.length === 0 && (
        <StatePanel
          icon="bell"
          title={unreadOnly ? 'No unread notifications' : 'Nothing here yet'}
          description={
            unreadOnly
              ? 'You are all caught up. Switch the filter to see older updates.'
              : 'Backend-generated updates about your complaints will appear here.'
          }
        />
      )}

      {unread.isError && (
        <div className="mb-4 rounded-xl border border-amber-200 bg-amber-50 px-3 py-2.5 text-sm text-amber-800">
          Unread count is unavailable right now. The notification list below is still current.
        </div>
      )}

      {(markOne.isError || markAll.isError) && (
        <div className="mb-4 rounded-xl border border-red-200 bg-red-50 px-3 py-2.5 text-sm text-red-700">
          {errorMessage(markOne.error ?? markAll.error, 'Could not update notifications')}
        </div>
      )}

      {items.length > 0 && (
        <div className="space-y-3">
          {items.map((notification) => (
            <Card
              key={notification.id}
              className={`p-5 transition ${notification.readAt ? 'opacity-75' : 'border-brand-200'}`}
            >
              <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
                <div className="min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <Badge tone={notification.readAt ? 'neutral' : 'success'}>
                      {notification.readAt ? 'Read' : 'Unread'}
                    </Badge>
                    {notification.deliveryStatus === 'FAILED' && (
                      <Badge tone="danger">Delivery failed</Badge>
                    )}
                    <Badge tone="neutral">{humanizeStatus(notification.type)}</Badge>
                    <span className="text-[11px] text-stone-500">
                      {formatDateTime(notification.createdAt)}
                    </span>
                  </div>
                  <h2 className="mt-2 text-sm font-semibold text-stone-900">{notification.title}</h2>
                  <p className="mt-1 text-sm leading-relaxed text-stone-600">{notification.body}</p>
                  {notification.complaintId && (
                    <Link
                      to={complaintPathForRole(user?.role, notification.complaintId)}
                      onClick={() => {
                        if (!notification.readAt) markOne.mutate(notification.id)
                      }}
                      className="mt-2 inline-flex items-center gap-1 text-xs font-semibold text-brand-700 hover:underline"
                    >
                      View complaint
                      {notification.complaintNumber ? ` ${notification.complaintNumber}` : ''}
                      <Icon name="arrow-right" className="h-3.5 w-3.5" />
                    </Link>
                  )}
                </div>
                {!notification.readAt && (
                  <Button
                    size="sm"
                    variant="secondary"
                    loading={markOne.isPending && markOne.variables === notification.id}
                    onClick={() => markOne.mutate(notification.id)}
                  >
                    Mark read
                  </Button>
                )}
              </div>
            </Card>
          ))}
        </div>
      )}
    </AppLayout>
  )
}
