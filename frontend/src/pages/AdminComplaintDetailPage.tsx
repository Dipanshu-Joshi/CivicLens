type ActionPanel = 'none' | 'classify' | 'assign' | 'reroute' | 'unassign' | 'review'

const severities: Severity[] = ['LOW', 'MEDIUM', 'HIGH', 'CRITICAL']

function Row({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="rounded-xl border border-stone-200 p-3">
      <dt className="text-[11px] font-semibold tracking-wide text-stone-500 uppercase">{label}</dt>
      <dd className="mt-1 text-sm text-stone-800">{children}</dd>
    </div>
  )
}

function reasonIsValid(reason: string): boolean {
  const length = reason.trim().length
  return length >= 10 && length <= 1000
}

function actionErrorText(error: unknown, fallback: string): string {
  const problem = problemFrom(error)
  const base = errorMessage(error, fallback)
  return problem.correlationId ? `${base} (correlation ${problem.correlationId})` : base
}

function parseCandidates(value: unknown): RoutingCandidate[] {
  if (Array.isArray(value)) return value as RoutingCandidate[]
  if (typeof value === 'string') {
    try {
      const parsed: unknown = JSON.parse(value)
      if (Array.isArray(parsed)) return parsed as RoutingCandidate[]
    } catch {
      return []
    }
  }
  return []
}

function AnalysisHistory({ entries }: { entries: AiAnalysisEntry[] }) {
  if (entries.length === 0) {
    return (
      <p className="mt-4 rounded-xl bg-stone-50 px-4 py-6 text-center text-xs text-stone-500">
        No AI analysis or classification overrides are recorded for this complaint.
      </p>
    )
  }
  return (
    <ol className="mt-4 space-y-4">
      {entries.map((entry, index) => {
        const isOverride = entry.source === 'ADMIN_OVERRIDE'
        return (
          <li key={entry.id} className="rounded-xl border border-stone-200 p-4">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex flex-wrap items-center gap-2">
                <Badge tone={isOverride ? 'warn' : 'info'}>
                  {isOverride ? 'Administrator override' : 'Generated by AI'}
                </Badge>
                <Badge tone="neutral">{humanizeStatus(entry.status)}</Badge>
                {entry.requiresHumanReview && <Badge tone="danger">Human review flagged</Badge>}
              </div>
              <span className="text-[11px] text-stone-500">
                #{entries.length - index} · {formatDateTime(entry.createdAt)}
              </span>
            </div>
            <dl className="mt-4 grid gap-3 sm:grid-cols-2">
              <Row label="Classification">
                {entry.categoryCode ?? 'Not identified'}
                {entry.subcategoryCode ? ` · ${entry.subcategoryCode}` : ''}
              </Row>
              <Row label="Severity">{entry.severity ?? 'Not assessed'}</Row>
              <Row label="Civic issue">
                {entry.isCivicIssue === null ? 'Not determined' : entry.isCivicIssue ? 'Yes' : 'No'}
              </Row>
              <Row label="Confidence">
                {entry.confidence === null ? '—' : `${Math.round(entry.confidence * 100)}%`}
              </Row>
              {entry.description && (
                <div className="sm:col-span-2">
                  <Row label={isOverride ? 'Corrected description' : 'AI description'}>
                    {entry.description}
                  </Row>
                </div>
              )}
              {isOverride && (
                <div className="sm:col-span-2">
                  <Row label="Override actor">
                    {entry.actorName ?? entry.actorRole ?? 'Administrator'}
                    {entry.actorRole ? ` · ${humanizeStatus(entry.actorRole)}` : ''}
                  </Row>
                  <div className="mt-3">
                    <Row label="Override reason">{entry.adminOverrideReason ?? 'No reason recorded'}</Row>
                  </div>
                </div>
              )}
            </dl>
          </li>
        )
      })}
    </ol>
  )
}

function RoutingHistory({ decisions }: { decisions: AdminRoutingDecision[] }) {
  if (decisions.length === 0) {
    return (
      <p className="mt-4 rounded-xl bg-stone-50 px-4 py-6 text-center text-xs text-stone-500">
        No routing decisions have been persisted for this complaint.
      </p>
    )
  }
  return (
    <ol className="mt-4 space-y-4">
      {decisions.map((decision, index) => {
        const candidates = parseCandidates(decision.candidates)
        return (
          <li key={decision.id ?? index} className="rounded-xl border border-stone-200 p-4">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div className="flex flex-wrap items-center gap-2">
                <Badge tone={decision.current ? 'success' : 'neutral'}>
                  {decision.current ? 'Current decision' : `Decision ${decisions.length - index}`}
                </Badge>
                <span className="text-sm font-semibold text-stone-900">
                  {decision.outcome ? humanizeStatus(decision.outcome) : 'Outcome not recorded'}
                </span>
              </div>
              <span className="text-[11px] text-stone-500">{formatDateTime(decision.createdAt)}</span>
            </div>
            <dl className="mt-3 grid gap-3 sm:grid-cols-2">
              <Row label="Decision reason">{decision.reason ?? 'No reason recorded'}</Row>
              <Row label="Selected department">
                {decision.selectedDepartmentId ?? 'None'}
              </Row>
              <Row label="Ruleset">{decision.rulesetVersion ?? '—'}</Row>
              <Row label="AI confidence">
                {decision.confidence === null || decision.confidence === undefined
                  ? '—'
                  : `${Math.round(decision.confidence * 100)}%`}
              </Row>
            </dl>
            <div className="mt-4">
              <p className="text-xs font-semibold text-stone-700">
                Evaluated candidates ({candidates.length})
              </p>
              {candidates.length === 0 ? (
                <p className="mt-2 text-xs text-stone-500">No eligible candidates were recorded.</p>
              ) : (
                <ul className="mt-2 space-y-2">
                  {candidates.map((candidate, candidateIndex) => (
                    <li
                      key={candidate.departmentId ?? candidate.departmentName ?? candidateIndex}
                      className="rounded-lg bg-stone-50 p-3"
                    >
                      <div className="flex flex-wrap items-center justify-between gap-2">
                        <span className="text-xs font-semibold text-stone-800">
                          {candidate.departmentName ?? candidate.departmentId ?? 'Unknown department'}
                          {candidate.atCapacity ? ' · at capacity' : ''}
                        </span>
                        <span className="text-xs font-semibold text-brand-700">
                          Score {candidate.total ?? 0}
                        </span>
                      </div>
                      <p className="mt-1 text-[11px] text-stone-500">
                        Geo {candidate.geoScore ?? 0} ({candidate.geoMatch ?? 'NONE'}) · Category{' '}
                        {candidate.catScore ?? 0} ({candidate.catMatch ?? 'NONE'}) · Priority{' '}
                        {candidate.priority ?? 0}
                      </p>
                      {(candidate.reasons ?? []).length > 0 && (
                        <ul className="mt-2 flex flex-wrap gap-1.5">
                          {candidate.reasons!.map((reason, reasonIndex) => (
                            <li key={`${reason}-${reasonIndex}`}>
                              <Badge tone="neutral">{reason}</Badge>
                            </li>
                          ))}
                        </ul>
                      )}
                    </li>
                  ))}
                </ul>
              )}
            </div>
          </li>
        )
      })}
    </ol>
  )
}

export default function AdminComplaintDetailPage() {
  const { id = '' } = useParams()
  const queryClient = useQueryClient()
  const [panel, setPanel] = useState<ActionPanel>('none')
  const [reason, setReason] = useState('')
  const [categoryCode, setCategoryCode] = useState('')
  const [subcategoryCode, setSubcategoryCode] = useState('')
  const [severity, setSeverity] = useState<Severity>('MEDIUM')
  const [description, setDescription] = useState('')
  const [departmentId, setDepartmentId] = useState('')
  const [requestId, setRequestId] = useState('')
  const [decision, setDecision] = useState<ReassignmentDecision>('APPROVED')
  const [formError, setFormError] = useState<string | null>(null)
  const [notice, setNotice] = useState<string | null>(null)
  const [actionError, setActionError] = useState<string | null>(null)

  const complaint = useQuery({
    queryKey: ['admin', 'complaints', id],
    queryFn: () => getAdminComplaint(id),
    retry: false,
  })
  const analyses = useQuery({
    queryKey: ['admin', 'complaints', id, 'analyses'],
    queryFn: () => listAdminAiAnalyses(id),
    retry: false,
  })
  const decisions = useQuery({
    queryKey: ['admin', 'complaints', id, 'routing-decisions'],
    queryFn: () => listAdminRoutingDecisions(id),
    retry: false,
  })
  const reassignments = useQuery({
    queryKey: ['admin', 'reassignment-requests'],
    queryFn: () => listAdminReassignmentRequests(),
    retry: false,
  })
  const departments = useQuery({
    queryKey: ['admin', 'departments'],
    queryFn: () => listAdminDepartments(),
    retry: false,
  })
  const imageIds = complaint.data?.images.map((image) => image.id).join(',') ?? ''
  const imageUrls = useQuery({
    queryKey: ['admin', 'complaints', id, 'image-urls', imageIds],
    queryFn: async () => {
      const entries = await Promise.all(
        (complaint.data?.images ?? []).map(async (image) => {
          const view = await getImageViewUrl(image.id)
          return [image.id, view.url] as const
        }),
      )
      return Object.fromEntries(entries) as Record<string, string>
    },
    enabled: Boolean(imageIds),
    retry: false,
    staleTime: 4 * 60_000,
  })

  const pendingRequests = (reassignments.data ?? []).filter(
    (request) => request.status === 'PENDING',
  )

  async function invalidate() {
    await Promise.all([
      queryClient.invalidateQueries({ queryKey: ['admin', 'complaints', id] }),
      queryClient.invalidateQueries({ queryKey: ['admin', 'complaints', id, 'analyses'] }),
      queryClient.invalidateQueries({ queryKey: ['admin', 'complaints', id, 'routing-decisions'] }),
      queryClient.invalidateQueries({ queryKey: ['admin', 'reassignment-requests'] }),
      queryClient.invalidateQueries({ queryKey: ['admin', 'complaints', 'queue'] }),
      queryClient.invalidateQueries({ queryKey: ['admin', 'overview'] }),
      queryClient.invalidateQueries({ queryKey: ['notifications', 'list'] }),
      queryClient.invalidateQueries({ queryKey: ['notifications', 'unread'] }),
    ])
  }

  function actionSettings(message: string) {
    return {
      onSuccess: async () => {
        setNotice(message)
        setActionError(null)
        setFormError(null)
        setPanel('none')
        setReason('')
        await invalidate()
      },
      onError: (error: unknown) => {
        setNotice(null)
        setActionError(actionErrorText(error, 'The administrative action could not be completed.'))
      },
    }
  }

  const classify = useMutation({
    mutationFn: (payload: {
      id: string
      body: {
        categoryCode: string
        subcategoryCode: string
        severity?: Severity
        description?: string
        reason: string
      }
    }) => overrideAdminClassification(payload.id, payload.body),
    ...actionSettings('Classification corrected and reroute requested.'),
  })
  const reroute = useMutation({
    mutationFn: (payload: { id: string; body: { reason: string } }) =>
      rerouteAdminComplaint(payload.id, payload.body),
    ...actionSettings('Forced reroute completed.'),
  })
  const assign = useMutation({
    mutationFn: (payload: { id: string; body: { departmentId: string; reason: string } }) =>
      assignAdminComplaint(payload.id, payload.body),
    ...actionSettings('Complaint manually assigned.'),
  })
  const unassign = useMutation({
    mutationFn: (payload: { id: string; body: { reason: string } }) =>
      unassignAdminComplaint(payload.id, payload.body),
    ...actionSettings('Complaint unassigned.'),
  })
  const review = useMutation({
    mutationFn: (payload: { id: string; body: { decision: ReassignmentDecision; reason: string } }) =>
      reviewAdminReassignment(payload.id, payload.body),
    ...actionSettings('Reassignment request reviewed.'),
  })

  const anyPending =
    classify.isPending || reroute.isPending || assign.isPending || unassign.isPending || review.isPending

  function togglePanel(next: ActionPanel) {
    setPanel((current) => (current === next ? 'none' : next))
    setFormError(null)
    setNotice(null)
    setActionError(null)
    setReason('')
  }

  function confirmAndRun(message: string, run: () => void) {
    if (!reasonIsValid(reason)) {
      setFormError('Enter a reason of 10–1000 characters. It is stored in the audit log.')
      return
    }
    if (!window.confirm(message)) return
    setFormError(null)
    run()
  }

  function submitClassification(event: FormEvent) {
    event.preventDefault()
    if (!categoryCode.trim() || !subcategoryCode.trim()) {
      setFormError('Category and subcategory codes are required.')
      return
    }
    confirmAndRun('Override the classification and force a reroute? AI history is preserved.', () => {
      if (!complaint.data) return
      setCategoryCode(categoryCode.trim())
      classify.mutate({
        id: complaint.data.id,
        body: {
          categoryCode: categoryCode.trim(),
          subcategoryCode: subcategoryCode.trim(),
          severity,
          description: description.trim() || undefined,
          reason: reason.trim(),
        },
      })
    })
  }

  function submitAssignment(event: FormEvent) {
    event.preventDefault()
    if (!departmentId) {
      setFormError('Choose a department before assigning manually.')
      return
    }
    confirmAndRun('Manually assign this complaint? This bypasses automated routing.', () => {
      if (!complaint.data) return
      assign.mutate({
        id: complaint.data.id,
        body: { departmentId, reason: reason.trim() },
      })
    })
  }

  function submitReroute(event: FormEvent) {
    event.preventDefault()
    confirmAndRun('Force a new routing decision for this complaint?', () => {
      if (!complaint.data) return
      reroute.mutate({ id: complaint.data.id, body: { reason: reason.trim() } })
    })
  }

  function submitUnassign(event: FormEvent) {
    event.preventDefault()
    confirmAndRun('Unassign this complaint? It will return to the governance queue.', () => {
      if (!complaint.data) return
      unassign.mutate({ id: complaint.data.id, body: { reason: reason.trim() } })
    })
  }

  function submitReview(event: FormEvent) {
    event.preventDefault()
    if (!requestId) {
      setFormError('Select a reassignment request to review.')
      return
    }
    confirmAndRun(`${humanizeStatus(decision)} this reassignment request?`, () => {
      review.mutate({ id: requestId, body: { decision, reason: reason.trim() } })
    })
  }

  if (complaint.isPending) {
    return (
      <AppLayout>
        <Card className="flex items-center justify-center gap-3 p-12 text-sm text-stone-500">
          <Spinner className="h-5 w-5 text-brand-600" />
          <span role="status">Loading complaint governance…</span>
        </Card>
      </AppLayout>
    )
  }

  if (complaint.isError || !complaint.data) {
    return (
      <AppLayout>
        <StatePanel
          tone="error"
          title={isNotFound(complaint.error) ? 'Complaint not found' : 'Could not load complaint'}
          description={errorMessage(complaint.error, 'This complaint could not be retrieved.')}
          action={
            <div className="flex flex-wrap items-center justify-center gap-2">
              <Button variant="secondary" onClick={() => void complaint.refetch()}>
                Try again
              </Button>
              <Link to="/admin/complaints">
                <Button variant="ghost">Back to global queue</Button>
              </Link>
            </div>
          }
        />
      </AppLayout>
    )
  }

  const data = complaint.data
  const urlById = imageUrls.data ?? {}

  return (
    <AppLayout>
      <PageHeader
        eyebrow="Super admin · complaint governance"
        title={data.complaintNumber}
        description={`Submitted ${formatDateTime(data.createdAt)} · AI output is advisory; only administrators assign departments.`}
        actions={
          <>
            <StatusBadge status={data.status} />
            <Badge tone="neutral">{humanizeStatus(data.severity)}</Badge>
            <Link to="/admin/complaints">
              <Button variant="secondary" size="sm" icon={<Icon name="arrow-left" className="h-4 w-4" />}>
                Queue
              </Button>
            </Link>
          </>
        }
      />

      {notice && (
        <div role="status" className="mb-5 rounded-xl border border-brand-200 bg-brand-50 px-3 py-2.5 text-sm text-brand-800">
          {notice}
        </div>
      )}
      {actionError && (
        <div role="alert" className="mb-5 rounded-xl border border-red-200 bg-red-50 px-3 py-2.5 text-sm text-red-700">
          {actionError}
        </div>
      )}

      <div className="grid gap-6 lg:grid-cols-[1.4fr_0.6fr]">
        <div className="space-y-6">
          <Card className="p-5 sm:p-6">
            <div className="flex flex-wrap items-center gap-2">
              <Badge tone="info">{data.categoryCode ?? 'Uncategorised'}</Badge>
              {data.subcategoryCode && <Badge tone="neutral">{data.subcategoryCode}</Badge>}
              {data.ward && <Badge tone="neutral">{data.ward}</Badge>}
              {data.zone && <Badge tone="neutral">{data.zone}</Badge>}
            </div>
            <h2 className="mt-4 text-base font-semibold text-stone-900">Citizen report</h2>
            <p className="mt-2 whitespace-pre-wrap text-sm leading-relaxed text-stone-700">
              {data.description}
            </p>
            {data.additionalInfo && (
              <p className="mt-3 rounded-xl bg-stone-50 p-3 text-sm leading-relaxed text-stone-600">
                {data.additionalInfo}
              </p>
            )}
            <dl className="mt-5 grid gap-3 sm:grid-cols-2">
              <Row label="Owning department">{data.departmentName ?? 'Unassigned'}</Row>
              <Row label="Resolution target">{formatDateTime(data.resolutionDueAt)}</Row>
              <Row label="Assigned at">{formatDateTime(data.assignedAt)}</Row>
              <Row label="Location">
                {data.latitude.toFixed(5)}, {data.longitude.toFixed(5)}
                {data.addressLine ? ` · ${data.addressLine}` : ''}
              </Row>
            </dl>
          </Card>

          <CitizenFeedbackCard feedback={data.feedback} />

          <Card className="p-5 sm:p-6">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div>
                <h2 className="text-base font-semibold text-stone-900">AI analysis history</h2>
                <p className="mt-1 text-xs text-stone-500">
                  Append-only. Original AI output is never replaced by an override.
                </p>
              </div>
              {analyses.isError && (
                <Button variant="ghost" size="sm" onClick={() => void analyses.refetch()}>
                  Retry
                </Button>
              )}
            </div>
            {analyses.isPending && (
              <p role="status" className="mt-4 text-xs text-stone-500">Loading AI history…</p>
            )}
            {analyses.isError && (
              <div role="alert" className="mt-4 rounded-xl border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700">
                {errorMessage(analyses.error, 'Could not load AI analysis history.')}
              </div>
            )}
            {analyses.data && <AnalysisHistory entries={analyses.data.analyses} />}
          </Card>

          <Card className="p-5 sm:p-6">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div>
                <h2 className="text-base font-semibold text-stone-900">Routing decision history</h2>
                <p className="mt-1 text-xs text-stone-500">
                  Every candidate score and reason is retained for audit.
                </p>
              </div>
              {decisions.isError && (
                <Button variant="ghost" size="sm" onClick={() => void decisions.refetch()}>
                  Retry
                </Button>
              )}
            </div>
            {decisions.isPending && (
              <p role="status" className="mt-4 text-xs text-stone-500">Loading routing decisions…</p>
            )}
            {decisions.isError && (
              <div role="alert" className="mt-4 rounded-xl border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700">
                {errorMessage(decisions.error, 'Could not load routing decisions.')}
              </div>
            )}
            {decisions.data && <RoutingHistory decisions={decisions.data} />}
          </Card>

          <Card className="p-5 sm:p-6">
            <h2 className="text-base font-semibold text-stone-900">Secure evidence</h2>
            {imageUrls.isError && (
              <div role="alert" className="mt-4 rounded-xl border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700">
                {errorMessage(imageUrls.error, 'Evidence previews could not be loaded.')}
                <Button variant="ghost" size="sm" className="ml-2" onClick={() => void imageUrls.refetch()}>
                  Retry
                </Button>
              </div>
            )}
            {data.images.length === 0 ? (
              <p className="mt-4 rounded-xl bg-stone-50 px-4 py-6 text-center text-xs text-stone-500">
                No images were attached to this complaint.
              </p>
            ) : (
              <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-3">
                {data.images.map((image) => {
                  const url = urlById[image.id]
                  return (
                    <div key={image.id}>
                      {url ? (
                        <a href={url} target="_blank" rel="noreferrer">
                          <img
                            src={url}
                            alt={`${humanizeStatus(image.imageKind)} evidence`}
                            className="h-28 w-full rounded-xl border border-stone-200 object-cover"
                          />
                        </a>
                      ) : (
                        <div className="flex h-28 items-center justify-center rounded-xl border border-dashed border-stone-300 bg-stone-50 text-xs text-stone-500">
                          {imageUrls.isPending ? 'Loading secure URL…' : 'Preview unavailable'}
                        </div>
                      )}
                      <p className="mt-1 text-[10px] text-stone-500">
                        {humanizeStatus(image.imageKind)} · {image.uploadStatus}
                      </p>
                    </div>
                  )
                })}
              </div>
            )}
          </Card>

          <Card className="p-5 sm:p-6">
            <h2 className="text-base font-semibold text-stone-900">Status history</h2>
            <div className="mt-6">
              <StatusTimeline entries={data.timeline} />
            </div>
          </Card>
        </div>

        <div className="space-y-6">
          <Card className="p-5">
            <h2 className="text-sm font-semibold text-stone-900">Governance actions</h2>
            <p className="mt-1 text-xs text-stone-500">
              Every action requires a reason and is written to the audit log.
            </p>
            <div className="mt-4 grid gap-2">
              <Button
                size="sm"
                variant={panel === 'classify' ? 'primary' : 'secondary'}
                disabled={anyPending}
                onClick={() => togglePanel('classify')}
              >
                Override classification
              </Button>
              <Button
                size="sm"
                variant={panel === 'assign' ? 'primary' : 'secondary'}
                disabled={anyPending}
                onClick={() => togglePanel('assign')}
              >
                Manually assign
              </Button>
              <Button
                size="sm"
                variant={panel === 'reroute' ? 'primary' : 'secondary'}
                disabled={anyPending}
                onClick={() => togglePanel('reroute')}
              >
                Force reroute
              </Button>
              <Button
                size="sm"
                variant={panel === 'unassign' ? 'danger' : 'secondary'}
                disabled={anyPending || !data.departmentId}
                onClick={() => togglePanel('unassign')}
              >
                Unassign
              </Button>
              <Button
                size="sm"
                variant={panel === 'review' ? 'primary' : 'secondary'}
                disabled={anyPending}
                onClick={() => togglePanel('review')}
              >
                Review reassignment
                {pendingRequests.length > 0 ? ` (${pendingRequests.length})` : ''}
              </Button>
            </div>

            {(panel === 'reroute' || panel === 'unassign') && (
              <form
                className="mt-4 space-y-3 border-t border-stone-200 pt-4"
                onSubmit={panel === 'reroute' ? submitReroute : submitUnassign}
              >
                <Field
                  label="Reason"
                  required
                  hint="10–1000 characters; stored in the audit log."
                  error={formError ?? undefined}
                >
                  <textarea
                    value={reason}
                    onChange={(event) => setReason(event.target.value)}
                    className={`${inputClass} min-h-20 resize-y`}
                    maxLength={1000}
                  />
                </Field>
                <div className="flex flex-wrap gap-2">
                  <Button type="submit" variant={panel === 'unassign' ? 'danger' : 'primary'} loading={anyPending}>
                    Confirm {panel === 'reroute' ? 'reroute' : 'unassign'}
                  </Button>
                  <Button type="button" variant="secondary" onClick={() => togglePanel('none')}>
                    Cancel
                  </Button>
                </div>
              </form>
            )}

            {panel === 'classify' && (
              <form className="mt-4 space-y-3 border-t border-stone-200 pt-4" onSubmit={submitClassification}>
                <Field label="Category code" required>
                  <input
                    value={categoryCode}
                    onChange={(event) => setCategoryCode(event.target.value)}
                    className={inputClass}
                    placeholder={data.categoryCode ?? 'ROAD'}
                  />
                </Field>
                <Field label="Subcategory code" required>
                  <input
                    value={subcategoryCode}
                    onChange={(event) => setSubcategoryCode(event.target.value)}
                    className={inputClass}
                    placeholder={data.subcategoryCode ?? 'POTHOLE'}
                  />
                </Field>
                <Field label="Severity" required>
                  <select
                    value={severity}
                    onChange={(event) => setSeverity(event.target.value as Severity)}
                    className={inputClass}
                  >
                    {severities.map((option) => (
                      <option key={option} value={option}>
                        {humanizeStatus(option)}
                      </option>
                    ))}
                  </select>
                </Field>
                <Field label="Corrected description" hint="Optional">
                  <textarea
                    value={description}
                    onChange={(event) => setDescription(event.target.value)}
                    className={`${inputClass} min-h-20 resize-y`}
                    maxLength={2000}
                  />
                </Field>
                <Field
                  label="Override reason"
                  required
                  hint="10–1000 characters; appears on the ADMIN_OVERRIDE row."
                  error={formError ?? undefined}
                >
                  <textarea
                    value={reason}
                    onChange={(event) => setReason(event.target.value)}
                    className={`${inputClass} min-h-20 resize-y`}
                    maxLength={1000}
                  />
                </Field>
                <div className="flex flex-wrap gap-2">
                  <Button type="submit" loading={anyPending}>Apply override</Button>
                  <Button type="button" variant="secondary" onClick={() => togglePanel('none')}>
                    Cancel
                  </Button>
                </div>
              </form>
            )}

            {panel === 'assign' && (
              <form className="mt-4 space-y-3 border-t border-stone-200 pt-4" onSubmit={submitAssignment}>
                <Field label="Assign to department" required hint={departments.isError ? 'Department list unavailable' : undefined}>
                  <select
                    value={departmentId}
                    onChange={(event) => setDepartmentId(event.target.value)}
                    className={inputClass}
                  >
                    <option value="">Select a department</option>
                    {departments.data?.map((department) => (
                      <option key={department.id} value={department.id}>
                        {department.name}
                      </option>
                    ))}
                  </select>
                </Field>
                <Field label="Reason" required hint="10–1000 characters; stored in the audit log." error={formError ?? undefined}>
                  <textarea
                    value={reason}
                    onChange={(event) => setReason(event.target.value)}
                    className={`${inputClass} min-h-20 resize-y`}
                    maxLength={1000}
                  />
                </Field>
                <div className="flex flex-wrap gap-2">
                  <Button type="submit" loading={anyPending}>Assign manually</Button>
                  <Button type="button" variant="secondary" onClick={() => togglePanel('none')}>
                    Cancel
                  </Button>
                </div>
              </form>
            )}

            {panel === 'review' && (
              <form className="mt-4 space-y-3 border-t border-stone-200 pt-4" onSubmit={submitReview}>
                {reassignments.isPending && (
                  <p role="status" className="text-xs text-stone-500">Loading reassignment requests…</p>
                )}
                {reassignments.isError && (
                  <div role="alert" className="rounded-xl border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700">
                    {errorMessage(reassignments.error, 'Could not load reassignment requests.')}
                    <Button variant="ghost" size="sm" className="ml-2" onClick={() => void reassignments.refetch()}>
                      Retry
                    </Button>
                  </div>
                )}
                {reassignments.data && pendingRequests.length === 0 && (
                  <p className="text-xs text-stone-500">No pending reassignment requests.</p>
                )}
                <Field label="Request" required>
                  <select
                    value={requestId}
                    onChange={(event) => setRequestId(event.target.value)}
                    className={inputClass}
                  >
                    <option value="">Select a pending request</option>
                    {pendingRequests.map((request) => (
                      <option key={request.id} value={request.id}>
                        {request.fromDepartmentId ?? 'Unassigned'} → {request.toDepartmentId}
                      </option>
                    ))}
                  </select>
                </Field>
                <Field label="Decision" required>
                  <select
                    value={decision}
                    onChange={(event) => setDecision(event.target.value as ReassignmentDecision)}
                    className={inputClass}
                  >
                    <option value="APPROVED">Approve</option>
                    <option value="REJECTED">Reject</option>
                  </select>
                </Field>
                <Field label="Review reason" required hint="10–1000 characters." error={formError ?? undefined}>
                  <textarea
                    value={reason}
                    onChange={(event) => setReason(event.target.value)}
                    className={`${inputClass} min-h-20 resize-y`}
                    maxLength={1000}
                  />
                </Field>
                <div className="flex flex-wrap gap-2">
                  <Button type="submit" loading={anyPending}>Submit review</Button>
                  <Button type="button" variant="secondary" onClick={() => togglePanel('none')}>
                    Cancel
                  </Button>
                </div>
              </form>
            )}
          </Card>

          <Card className="p-5">
            <h2 className="text-sm font-semibold text-stone-900">Current classification</h2>
            <dl className="mt-4 space-y-3 text-sm">
              <Row label="Category">{data.categoryCode ?? 'Not identified'}</Row>
              <Row label="Subcategory">{data.subcategoryCode ?? 'Not identified'}</Row>
              <Row label="Severity">{humanizeStatus(data.severity)}</Row>
              <Row label="AI summary">
                {data.analysis?.description ?? 'No advisory analysis is attached.'}
              </Row>
            </dl>
          </Card>
        </div>
      </div>
    </AppLayout>
  )
}
